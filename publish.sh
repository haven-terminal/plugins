#!/bin/sh
# Build every plugin and lay out a signed repository for them.
#
#     plugins/publish.sh <output-dir> [fingerprint]
#
# What comes out is exactly what `haven plugin repo add` expects:
#
#     plugins.yaml        the index, generated from each plugin's MANIFEST.yaml
#     plugins.yaml.sig    a detached signature, if a fingerprint was given
#     key.asc             that key's public half
#     pool/<name>-<v>.tar.gz
#
# The signing key is yours and this script never goes looking for one: pass
# a fingerprint and it signs, pass nothing and it stops with the one command
# left to run. A release tool that quietly picks a key is a release tool
# that signs with the wrong one.
set -eu

out=${1:?usage: publish.sh <output-dir> [fingerprint]}
fingerprint=${2:-}
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

have() { command -v "$1" >/dev/null 2>&1; }
have cargo || { echo "publish.sh needs cargo" >&2; exit 1; }
have tar || { echo "publish.sh needs tar" >&2; exit 1; }

# `sha256sum` on Linux, `shasum -a 256` on macOS. One of them is there.
if have sha256sum; then
    hash_of() { sha256sum "$1" | cut -d' ' -f1; }
elif have shasum; then
    hash_of() { shasum -a 256 "$1" | cut -d' ' -f1; }
else
    echo "publish.sh needs sha256sum or shasum" >&2
    exit 1
fi

echo "== building"
( cd "$here" && cargo build --release --target wasm32-wasip2 )
built=$here/target/wasm32-wasip2/release

mkdir -p "$out/pool"
index=$out/plugins.yaml

{
    echo "# Haven plugins. Generated by plugins/publish.sh — do not edit by hand."
    echo "repo: haven"
    echo "description: the plugins that ship with Haven"
    echo "plugins:"
} > "$index"

count=0
for dir in "$here"/useful/*/; do
    name=$(basename "$dir")
    manifest=$dir/MANIFEST.yaml
    [ -f "$manifest" ] || { echo "   $name has no MANIFEST.yaml, skipping" >&2; continue; }

    # What the host will load, and therefore the name the file must have
    # inside the artifact. The manifest is the authority.
    component=$(sed -n 's/^ *entry: *//p' "$manifest" | head -1)
    [ -n "$component" ] || { echo "   $name: no entry in MANIFEST.yaml" >&2; exit 1; }

    # What cargo actually produced, which is not always that: a library
    # target cannot have a hyphen in its name, so `git-stash` builds as
    # `git_stash.wasm`. Both spellings are tried and the file is packed
    # under the name the manifest promised, so the published artifact
    # matches the index whichever way the author wrote it.
    underscored=$(printf '%s' "$component" | tr '-' '_')
    if [ -f "$built/$component" ]; then
        artifact=$built/$component
    elif [ -f "$built/$underscored" ]; then
        artifact=$built/$underscored
    else
        echo "   $name: neither $component nor $underscored was built" >&2
        exit 1
    fi

    version=$(sed -n 's/^ *version: *//p' "$manifest" | head -1)
    [ -n "$version" ] || { echo "   $name: no version in MANIFEST.yaml" >&2; exit 1; }

    # One component per artifact, at the root, so `entry` is a bare name.
    tarball=pool/$name-$version.tar.gz
    staging=$(mktemp -d)
    cp "$artifact" "$staging/$component"
    [ -f "$dir/README.md" ] && cp "$dir/README.md" "$staging/README.md"
    # Fixed times, ownership and order, so building twice gives the same
    # bytes and so the hash means something you can check.
    ( cd "$staging" && tar --sort=name --mtime='@0' --owner=0 --group=0 \
        --numeric-owner -cf - . 2>/dev/null || tar -cf - . ) | gzip -n > "$out/$tarball"
    rm -rf "$staging"

    sum=$(hash_of "$out/$tarball")

    # Normalised into the index rather than concatenated.
    #
    # A manifest is written by hand and both shapes turn up: a bare
    # `name: x` at column zero, and a `- name: x` already indented as a
    # list item. Appending either verbatim produces a file that is not
    # the YAML it looks like — the first version of this script did, and
    # Haven refused the result with `plugins: has nothing under it`,
    # which is exactly the right complaint about the wrong file. So the
    # keys are read and re-emitted at the one indentation the index uses,
    # with the two fields only a publisher can know filled in.
    awk -v file="$tarball" -v sum="$sum" '
        # A comment belongs to the author, not to the index.
        /^[[:space:]]*#/ { next }
        /^[[:space:]]*$/ { next }
        {
            line = $0
            sub(/^[[:space:]]*/, "", line)
            sub(/^- /, "", line)
            key = line
            sub(/:.*$/, "", key)

            # Everything an entry has at its top level. Anything else is
            # inside the capabilities block, which is the only nesting
            # the schema has.
            top = (key == "name" || key == "version" || key == "summary" \
                || key == "file" || key == "sha256" || key == "entry" \
                || key == "events" || key == "capabilities")

            if (key == "file") { line = "file: " file }
            if (key == "sha256") { line = "sha256: " sum }

            if (key == "name") { printf "  - %s\n", line; next }
            if (top) { printf "    %s\n", line; next }
            printf "      %s\n", line
        }
    ' "$manifest" >> "$index"
    count=$((count + 1))
    echo "   $name $version  $tarball"
done

[ "$count" -gt 0 ] || { echo "no plugins found under $here/useful" >&2; exit 1; }
echo "== $count plugin(s) in $index"

if [ -z "$fingerprint" ]; then
    cat <<MSG

Not signed. An unsigned index is one Haven will refuse, so finish it with
your own key:

    gpg --armor --export <your-fingerprint> > $out/key.asc
    gpg --detach-sign --armor -o $out/plugins.yaml.sig $index

or run this again with the fingerprint as the second argument.
MSG
    exit 0
fi

have gpg || { echo "signing needs gpg" >&2; exit 1; }
gpg --armor --export "$fingerprint" > "$out/key.asc"
rm -f "$out/plugins.yaml.sig"
gpg --batch --detach-sign --armor --local-user "$fingerprint" \
    -o "$out/plugins.yaml.sig" "$index"
gpg --verify "$out/plugins.yaml.sig" "$index"

cat <<MSG

Signed by $fingerprint.

To check it the way a user will, against a throwaway configuration:

    haven plugin repo add $out --key $fingerprint --name test --root /tmp/try
    haven plugin --root /tmp/try search
MSG
